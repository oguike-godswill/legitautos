async function seed() {
  try {
    const { dbConnect } = await import("../lib/dbConnect");
    await dbConnect();
    console.log("Connected to MongoDB");

    // Clear existing data
    await Car.deleteMany({});
    await Brand.deleteMany({});
    console.log("Cleared existing data");

    // Extract unique brands and count of cars for each brand dynamically
    const brandCounts: Record<string, number> = {};
    for (const car of sampleCars) {
      brandCounts[car.brand] = (brandCounts[car.brand] || 0) + 1;
    }

    const uniqueBrands = Object.keys(brandCounts).map((brandName) => {
      const brandCountries: Record<string, string> = {
        Toyota: "Japan",
        Honda: "Japan",
        Lexus: "Japan",
        "Mercedes-Benz": "Germany",
        BMW: "Germany",
        Audi: "Germany",
        Ford: "USA",
        Hyundai: "South Korea",
        Kia: "South Korea",
        Nissan: "Japan",
        Volkswagen: "Germany",
        Porsche: "Germany",
      };
      return {
        name: brandName,
        slug: slugify(brandName, { lower: true }),
        country: brandCountries[brandName] || "Unknown",
        carCount: brandCounts[brandName],
      };
    });

    const brandDocs = await Brand.insertMany(uniqueBrands);
    console.log(`Seeded ${brandDocs.length} brands`);

    // Seed cars
    const carDocs = await Car.insertMany(
      sampleCars.map((car) => ({
        ...car,
        slug: slugify(`${car.brand}-${car.model}-${car.year}-${Date.now()}`, { lower: true }),
      }))
    );
    console.log(`Seeded ${carDocs.length} cars`);

    console.log("\n✅ Seed completed successfully!");
    console.log("\nSample data:");
    console.log(`- ${carDocs.length} cars`);
    console.log(`- ${brandDocs.length} brands`);
    console.log("\nYou can now start the app and visit:");
    console.log("- http://localhost:3000 (Home)");
    console.log("- http://localhost:3000/cars (Car Listings)");
    console.log("- http://localhost:3000/admin (Admin Dashboard)");

    await mongoose.disconnect();
    process.exit(0);
  } catch (error) {
    console.error("❌ Seed failed:", error);
    process.exit(1);
  }
}

seed();
